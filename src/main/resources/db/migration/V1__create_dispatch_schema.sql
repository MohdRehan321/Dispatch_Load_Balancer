
CREATE TABLE dispatch_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Only one active dispatch batch is allowed.
CREATE UNIQUE INDEX ux_dispatch_batches_one_active
    ON dispatch_batches (is_active)
    WHERE is_active = TRUE;


CREATE TABLE delivery_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    order_id VARCHAR(100) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    address VARCHAR(500) NOT NULL,
    package_weight NUMERIC(12, 3) NOT NULL,
    priority VARCHAR(20) NOT NULL,

    CONSTRAINT fk_orders_batch
        FOREIGN KEY (batch_id)
        REFERENCES dispatch_batches(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_orders_batch_order
        UNIQUE (batch_id, order_id),

    CONSTRAINT chk_order_weight
        CHECK (package_weight > 0),

    CONSTRAINT chk_order_priority
        CHECK (priority IN ('HIGH', 'MEDIUM', 'LOW')),

    CONSTRAINT chk_order_latitude
        CHECK (latitude BETWEEN -90 AND 90),

    CONSTRAINT chk_order_longitude
        CHECK (longitude BETWEEN -180 AND 180)
);

CREATE INDEX idx_orders_batch_priority
    ON delivery_orders(batch_id, priority);


CREATE TABLE vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    vehicle_id VARCHAR(100) NOT NULL,
    capacity NUMERIC(12, 3) NOT NULL,
    current_latitude DOUBLE PRECISION NOT NULL,
    current_longitude DOUBLE PRECISION NOT NULL,
    current_address VARCHAR(500) NOT NULL,

    CONSTRAINT fk_vehicles_batch
        FOREIGN KEY (batch_id)
        REFERENCES dispatch_batches(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_vehicles_batch_vehicle
        UNIQUE (batch_id, vehicle_id),

    CONSTRAINT chk_vehicle_capacity
        CHECK (capacity > 0),

    CONSTRAINT chk_vehicle_latitude
        CHECK (current_latitude BETWEEN -90 AND 90),

    CONSTRAINT chk_vehicle_longitude
        CHECK (current_longitude BETWEEN -180 AND 180)
);

CREATE INDEX idx_vehicles_batch
    ON vehicles(batch_id);
